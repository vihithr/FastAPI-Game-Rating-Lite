"""Extract the lucide icons this site actually uses and emit a minimal runtime.

Replaces the 540 KB `vendor/lucide.min.js` bundle (101 KB gzipped, loaded on every
page) with a ~14 KB self-contained renderer that keeps the same `lucide.createIcons()`
API used by the templates.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "app" / "static" / "vendor" / "lucide.min.js"
OUT = ROOT / "app" / "static" / "js" / "icons.js"

NAMES = [
    "arrow-right", "award", "bar-chart-2", "bar-chart-3", "book-open", "building-2",
    "calendar",
    "check", "check-circle", "chevron-down", "chevron-left", "chevron-right",
    "chevron-up", "clock", "edit",
    "file-pen-line", "file-plus-2", "file-text", "folder-open", "gamepad-2", "gem",
    "gift", "grid-3x3", "grip", "grip-vertical", "home", "image", "image-off",
    "info", "layout-grid",
    "list", "log-in", "log-out", "lock", "mail", "menu", "message-circle", "moon", "plus",
    "plus-circle", "radar", "save", "search", "send", "sliders-horizontal",
    "sparkles", "star", "sun", "swords",
    "tags", "trash-2", "trending-up", "user", "user-plus", "users", "x",
]

RUNTIME = """/* Generated by tools/build_icons.py - do not edit by hand.
 * Minimal stand-in for lucide v0.523.0 (ISC) exposing only the icons this site uses.
 */
(function () {
  'use strict';

  var ICONS = __DATA__;

  var SVG_NS = 'http://www.w3.org/2000/svg';
  var DEFAULTS = {
    xmlns: SVG_NS,
    width: '24',
    height: '24',
    viewBox: '0 0 24 24',
    fill: 'none',
    stroke: 'currentColor',
    'stroke-width': '2',
    'stroke-linecap': 'round',
    'stroke-linejoin': 'round'
  };

  function escapeAttr(value) {
    return String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;')
      .replace(/</g, '&lt;').replace(/>/g, '&gt;');
  }

  function renderNodes(nodes) {
    var html = '';
    for (var i = 0; i < nodes.length; i++) {
      var node = nodes[i];
      var tag = node[0];
      var attrs = node[1] || {};
      var children = node[2];
      html += '<' + tag;
      for (var key in attrs) {
        if (Object.prototype.hasOwnProperty.call(attrs, key)) {
          html += ' ' + key + '="' + escapeAttr(attrs[key]) + '"';
        }
      }
      if (children && children.length) {
        html += '>' + renderNodes(children) + '</' + tag + '>';
      } else {
        html += '></' + tag + '>';
      }
    }
    return html;
  }

  function toSvg(name, nodes, source) {
    var svg = document.createElementNS(SVG_NS, 'svg');
    for (var key in DEFAULTS) {
      if (Object.prototype.hasOwnProperty.call(DEFAULTS, key)) {
        svg.setAttribute(key, DEFAULTS[key]);
      }
    }
    if (source) {
      var attrs = source.attributes;
      for (var i = 0; i < attrs.length; i++) {
        var attr = attrs[i];
        if (attr.name === 'data-lucide' || attr.name === 'class') continue;
        svg.setAttribute(attr.name, attr.value);
      }
      var cls = source.getAttribute('class');
      svg.setAttribute('class', ('lucide lucide-' + name + (cls ? ' ' + cls : '')).trim());
    } else {
      svg.setAttribute('class', 'lucide lucide-' + name);
    }
    svg.setAttribute('aria-hidden', 'true');
    svg.innerHTML = renderNodes(nodes);
    return svg;
  }

  function createIcons(options) {
    var icons = (options && options.icons) || ICONS;
    var root = (options && options.root) || document;
    var placeholders = root.querySelectorAll('[data-lucide]');
    for (var i = 0; i < placeholders.length; i++) {
      var el = placeholders[i];
      var name = el.getAttribute('data-lucide');
      var nodes = icons[name];
      if (!nodes) continue;
      el.parentNode.replaceChild(toSvg(name, nodes, el), el);
    }
  }

  window.lucide = { createIcons: createIcons, icons: ICONS, toSvg: toSvg };
  window.createIcons = createIcons;

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function () { createIcons(); });
  } else {
    createIcons();
  }
})();
"""


def to_pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("-"))


def find_node_array(text: str, const_name: str):
    """Return the balanced bracket literal assigned to `const <name> = [...]`."""
    for m in re.finditer(r"(?:const|var|let)\s+" + re.escape(const_name) + r"\s*=\s*\[", text):
        start = m.end() - 1
        depth = 0
        in_str = None
        i = start
        while i < len(text):
            ch = text[i]
            if in_str:
                if ch == "\\":
                    i += 2
                    continue
                if ch == in_str:
                    in_str = None
            elif ch in "\"'`":
                in_str = ch
            elif ch == "[":
                depth += 1
            elif ch == "]":
                depth -= 1
                if depth == 0:
                    return text[start:i + 1]
            i += 1
    return None


def parse_js_array(literal: str):
    normalized = re.sub(r"([{\[,])\s*([A-Za-z_$][\w$]*)\s*:", r'\1"\2":', literal)
    return json.loads(normalized.replace("'", '"'))


def parse_alias_map(text: str) -> dict:
    """Parse the export map that resolves deprecated names (Edit -> SquarePen)."""
    anchor = re.search(r"\bEdit:\s*SquarePen\b", text)
    if not anchor:
        return {}
    start = text.rindex("{", 0, anchor.start())
    depth = 0
    for j in range(start, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                block = text[start:j + 1]
                break
    else:
        return {}
    return dict(re.findall(r"\b([A-Za-z0-9_$]+)\s*:\s*([A-Za-z0-9_$]+)\b", block))


def main() -> int:
    text = SRC.read_text(encoding="utf-8")
    aliases = parse_alias_map(text)

    icons = {}
    missing = []
    for name in NAMES:
        pascal = to_pascal(name)
        candidates = [pascal, aliases.get(pascal), aliases.get(name)]
        for cand in filter(None, candidates):
            literal = find_node_array(text, cand)
            if not literal:
                continue
            try:
                icons[name] = parse_js_array(literal)
                break
            except json.JSONDecodeError:
                continue
        else:
            missing.append(name)

    if missing:
        raise SystemExit(f"could not extract: {', '.join(missing)}")

    data = json.dumps(icons, separators=(",", ":"), ensure_ascii=False)
    OUT.write_text(RUNTIME.replace("__DATA__", data), encoding="utf-8")
    size = OUT.stat().st_size
    print(f"{len(icons)} icons -> {OUT.relative_to(ROOT)} ({size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
